-- 事件审计表：对账与重放依据（对齐 ECHI「记录一切、含重复」的落盘模型）。
-- 处理前先写 disposition=RECEIVED，处理完成后回填处置结果；
-- 进程崩溃时留下 RECEIVED 行，可作为补推对账依据。
-- 不设 event_id 唯一约束：幂等去重由 Redis 承担，DB 保留合法重推（400/409 清占位后重发）的完整轨迹。
CREATE TABLE IF NOT EXISTS agent_event_audit (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         VARCHAR(128),
    agent_id         VARCHAR(64)  NOT NULL,
    event_type       VARCHAR(64)  NOT NULL,
    event_time_ms    BIGINT       NOT NULL,
    seq              BIGINT,
    call_id          VARCHAR(128),
    disposition      VARCHAR(16)  NOT NULL,
    detail           VARCHAR(512),
    prev_state       VARCHAR(16),
    new_state        VARCHAR(16),
    closed_window_ms BIGINT,
    out_of_order     BOOLEAN      NOT NULL DEFAULT FALSE,
    state_unchanged  BOOLEAN      NOT NULL DEFAULT FALSE,
    payload          CLOB,
    received_at_ms   BIGINT       NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_audit_agent_time ON agent_event_audit (agent_id, event_time_ms);
CREATE INDEX IF NOT EXISTS idx_audit_received   ON agent_event_audit (received_at_ms);
CREATE INDEX IF NOT EXISTS idx_audit_disp       ON agent_event_audit (disposition, received_at_ms);
